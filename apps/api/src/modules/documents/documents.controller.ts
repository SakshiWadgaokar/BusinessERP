import { Controller, Get, Param, Query, Res } from '@nestjs/common';
import { Response } from 'express';
import { PERMISSIONS, paginationQuerySchema } from '@erp/shared';
import { z } from 'zod';
import { CurrentUser, Public, RequirePermissions } from '../../common/decorators/auth.decorators';
import { ZodValidationPipe } from '../../common/pipes/zod-validation.pipe';
import { AuthenticatedUser } from '../../common/types/auth-user.type';
import { DocumentsService } from './documents.service';

const docSearchQuery = paginationQuerySchema.extend({
  documentType: z.string().optional(),
  dealerId: z.string().uuid().optional(),
  entityType: z.string().optional(),
});

@Controller('documents')
export class DocumentsController {
  constructor(private readonly documentsService: DocumentsService) {}

  @Get('search')
  @RequirePermissions(PERMISSIONS.DOCUMENTS_READ)
  search(
    @Query(new ZodValidationPipe(docSearchQuery)) query: any,
    @CurrentUser() actor: AuthenticatedUser,
  ) {
    return this.documentsService.search(query, actor);
  }

  @Get('invoices/:invoiceId/pdf')
  @RequirePermissions(PERMISSIONS.INVOICES_READ)
  getInvoicePdf(@Param('invoiceId') invoiceId: string, @CurrentUser() actor: AuthenticatedUser) {
    return this.documentsService.getOrGenerateInvoicePdf(invoiceId, actor);
  }

  @Get('payments/:paymentId/receipt-pdf')
  @RequirePermissions(PERMISSIONS.PAYMENTS_READ)
  getReceiptPdf(@Param('paymentId') paymentId: string, @CurrentUser() actor: AuthenticatedUser) {
    return this.documentsService.getOrGenerateReceiptPdf(paymentId, actor);
  }

  @Get('dispatches/:dispatchId/challan-pdf')
  @RequirePermissions(PERMISSIONS.DISPATCHES_READ)
  getChallanPdf(@Param('dispatchId') dispatchId: string, @CurrentUser() actor: AuthenticatedUser) {
    return this.documentsService.getOrGenerateChallanPdf(dispatchId, actor);
  }

  @Get(':id/download-url')
  @RequirePermissions(PERMISSIONS.DOCUMENTS_READ)
  getDownloadUrl(@Param('id') id: string, @CurrentUser() actor: AuthenticatedUser) {
    return this.documentsService.getSignedDownloadUrl(id, actor);
  }

  /**
   * Private HMAC-signed streaming endpoint for local_private storage mode.
   * Requires a valid, non-expired cryptographic signature generated by StorageService.
   */
  @Public()
  @Get(':id/stream')
  async streamLocal(
    @Param('id') id: string,
    @Query('exp') exp: string,
    @Query('sig') sig: string,
    @Res() res: Response,
  ) {
    const { doc, buffer } = await this.documentsService.streamVerifiedLocalDocument(
      id,
      Number(exp),
      sig,
    );
    res.setHeader('Content-Type', doc.mimeType);
    res.setHeader('Content-Disposition', `inline; filename="${doc.fileName.replace(/"/g, '')}"`);
    res.setHeader('Cache-Control', 'private, no-store');
    res.send(buffer);
  }
}
